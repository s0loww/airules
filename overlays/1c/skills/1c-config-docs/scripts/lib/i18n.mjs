// Key groups each script needs (checked up front so a missing override fails fast, exit 2).
const pick = (re) => Object.keys(BUILTIN.en).filter((k) => re.test(k));
export const GROUPS = {
  docx: ['langLabel', 'page', 'of', 'contents', 'figure', 'source', 'commit', 'document', 'note', 'warn', 'interactive', 'glossNote', 'tocHint'],
  status: ['statusNew', 'statusModified', 'statusCore', 'statusLegacy'],
  reference: [...pick(/^(ref|lbl|part)/)],
  // required only when the inventory describes a configuration extension (header.extension)
  extension: ['statusAdopted', ...pick(/^ext/)],
  // required only with reference.kindDetails (default on) / a purposes.json
  kindDetails: [...pick(/^kd/)],
  purposes: [...pick(/^pur/)],
  nav: [...pick(/^nav/), 'dateFormat'],
  readme: [...pick(/^rm/), 'dateFormat'],
};

const isObj = (v) => v !== null && typeof v === 'object' && !Array.isArray(v);

/** Fill `{a}` / `{a.b}` placeholders. Missing values are a ConfigError (exit 2). */
export function fmt(tpl, args, where = 'template') {
  return String(tpl).replace(/\{([A-Za-z_]\w*(?:\.[A-Za-z_]\w*)*)\}/g, (m, key) => {
    let v = args;
    for (const part of key.split('.')) v = v == null ? undefined : v[part];
    if (v === undefined || v === null) throw new ConfigError(`${where}: placeholder {${key}} has no value (check uiStrings)`);
    return String(v);
  });
}

/** Merged UI table for one language: built-in + config override. */
export function uiFor(cfg, code) {
  const base = BUILTIN[code];
  const over = cfg.uiStrings && cfg.uiStrings[code];
  if (!base && !over) {
    throw new ConfigError(`no built-in UI strings for language "${code}" (built-in: ${Object.keys(BUILTIN).join(', ')}); add uiStrings.${code} to the config`);
  }
  if (over !== undefined && !isObj(over)) throw new ConfigError(`uiStrings.${code}: must be an object`);
  const merged = { ...(base || {}) };
  for (const [k, v] of Object.entries(over || {})) {
    if ((k === 'lang' || k === 'kinds') && isObj(v)) {
      merged[k] = { ...(merged[k] || {}) };
      for (const [k2, v2] of Object.entries(v)) merged[k][k2] = k === 'lang' && isObj(v2) ? { ...(merged[k][k2] || {}), ...v2 } : v2;
    } else merged[k] = v;
  }
  const U = {
    code, table: merged, builtin: !!base,
    has: (k) => merged[k] !== undefined,
    raw(k) {
      if (merged[k] === undefined) throw new ConfigError(`UI string uiStrings.${code}.${k} is missing${base ? '' : ` (no built-in table for "${code}")`}`);
      return merged[k];
    },
    t(k, args = {}) { return fmt(U.raw(k), args, `uiStrings.${code}.${k}`); },
    lang(of) {
      const f = merged.lang && merged.lang[of];
      if (!isObj(f)) throw new ConfigError(`uiStrings.${code}.lang.${of} is missing: names of language "${of}" as written in "${code}" (e.g. {"Name": "..."})`);
      return f;
    },
    kind(kind, plural = false) {
      const k = merged.kinds && merged.kinds[kind];
      if (!Array.isArray(k) || k.length < 2) throw new ConfigError(`uiStrings.${code}.kinds.${kind} is missing ([singular, plural])`);
      return k[plural ? 1 : 0];
    },
    date(iso) {
      const [y, m, d] = String(iso).split('-');
      return String(U.raw('dateFormat')).replace('YYYY', y).replace('MM', m).replace('DD', d);
    },
  };
  return U;
}

/** Check that every key of the given groups exists for every language; throws ConfigError listing gaps. */
export function requireUi(cfg, codes, groups) {
  const problems = [];
  const uis = {};
  for (const code of codes) {
    const U = uiFor(cfg, code);
    uis[code] = U;
    const missing = [];
    for (const g of groups) for (const k of GROUPS[g]) if (!U.has(k)) missing.push(k);
    if (missing.length) problems.push(`language "${code}"${U.builtin ? '' : ' (no built-in table)'}: missing uiStrings.${code}.{${missing.slice(0, 25).join(', ')}${missing.length > 25 ? `, … +${missing.length - 25}` : ''}}`);
    // language names of every configured language are needed by docx (glossary) and reference headers
    for (const other of cfg.langs) {
      const f = U.table.lang && U.table.lang[other];
      if (!isObj(f) || typeof f.Name !== 'string') problems.push(`language "${code}": missing uiStrings.${code}.lang.${other}.Name`);
    }
  }
  if (problems.length) throw new ConfigError(`incomplete UI strings:\n  - ${problems.join('\n  - ')}`);
  return uis;
}
